"""Helpers for a results folder (``<output>/<name>/``) that may already exist."""

import csv
import shutil
from datetime import datetime
from pathlib import Path

# Files GreenBench itself writes into a results folder. Only these are ever deleted.
OWN_FILES = ("data.csv", "results.csv", "plan.json", "output.log", "warmup.csv")
OWN_PATTERNS = ("energy_*.png", "run_*.csv")  # plots, and leftovers of a crashed run
OWN_DIRS = ("raw",)
# Written again at the end of every run, so a stale copy must never survive an early failure.
DERIVED_FILES = ("results.csv",)
DERIVED_PATTERNS = ("energy_*.png",)

MISSING, EMPTY, HAS_RESULTS, FOREIGN = "missing", "empty", "has_results", "foreign"


def _own_paths(folder: Path, files, patterns, dirs=()) -> list[Path]:
    found = [folder / name for name in files if (folder / name).is_file() or (folder / name).is_symlink()]
    for pattern in patterns:
        found.extend(p for p in folder.glob(pattern) if p.is_file() or p.is_symlink())
    found.extend(folder / name for name in dirs if (folder / name).is_dir() and not (folder / name).is_symlink())
    return sorted(set(found))


def own_artifacts(folder: Path) -> list[Path]:
    return _own_paths(folder, OWN_FILES, OWN_PATTERNS, OWN_DIRS)


def classify(folder: Path) -> str:
    """MISSING, EMPTY (reuse silently), HAS_RESULTS (ask first) or FOREIGN (not ours: refuse)."""
    if not folder.exists():
        return MISSING
    if not folder.is_dir():
        return FOREIGN
    if not any(folder.iterdir()):
        return EMPTY
    return HAS_RESULTS if own_artifacts(folder) else FOREIGN


def describe(folder: Path) -> str:
    """One line for the overwrite prompt: what is about to be deleted."""
    parts = []
    data = folder / "data.csv"
    if data.is_file():
        with open(data, newline="", encoding="utf-8") as f:
            parts.append(f"{max(sum(1 for _ in csv.reader(f)) - 1, 0)} recorded runs")
    if (folder / "results.csv").is_file():
        parts.append("results.csv")
    if any(folder.glob("energy_*.png")):
        parts.append("plots")
    if (folder / "raw").is_dir():
        parts.append("raw telemetry")
    newest = max(p.stat().st_mtime for p in own_artifacts(folder))
    parts.append(f"last modified {datetime.fromtimestamp(newest):%Y-%m-%d %H:%M}")
    return ", ".join(parts)


def _remove(paths: list[Path]) -> None:
    for path in paths:
        if path.is_dir() and not path.is_symlink():
            shutil.rmtree(path)
        else:
            path.unlink(missing_ok=True)  # a symlink is removed itself, never followed


def clear_results(folder: Path) -> None:
    """Delete everything GreenBench wrote here (and nothing else)."""
    _remove(own_artifacts(folder))


def clear_derived(folder: Path) -> None:
    """Delete only outputs that are regenerated by the analysis (keeps measurements for --resume)."""
    _remove(_own_paths(folder, DERIVED_FILES, DERIVED_PATTERNS))
